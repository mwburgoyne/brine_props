"""Bignell (1987) H2 densities reduced to apparent molar volumes: a HELD-OUT check
of the H2 route (never fitted). Paper 61, Table I, 50 density differences of
H2-saturated water at 3.87-25.02 degC and atmospheric pressure, verified in
`bignell1987_density_data.json` (`ingest_bignell1987.py --check`).

Reduction (per temperature group, mean of the repeats): the dissolved amount at
0.101325 MPa total pressure comes from the Soreide-Whitson flash of the
companion refresh (framework='default', y_H2 = 1; the flash carries the water
vapour), and the exact inversion of the mass-volume balance gives

    V_phi = ((1 + m M)/(rho_w + drho) - 1/rho_w) / m       [m3/mol]

with m the H2 molality, M in kg/mol, rho_w from IAPWS-IF97 and drho Bignell's
density difference. The solubility is the weak link: +/-3% in x moves V_phi by
-/+0.6 cm3/mol, and Bignell's own literature Henry constant gives him 21.6 at
5 degC where the flash gives 23.0. The values are therefore held out, with the
solubility dependence stated, not fitted.

Result (2026-09-06): 21.3-23.0 cm3/mol, essentially flat (-0.07 cm3/mol/K),
where the route gives 24.1-25.0 rising; the route is +5% at 4 degC and +16% at
25 degC. At 25 degC Bignell's 21.6 sits below all three direct determinations
that set the shift (Zhou 23.1, Tiepel 25.2, Moore 26.7): the H2 inter-laboratory
spread at 298 K is 21.5-26.7 cm3/mol. A shift fitted to Bignell alone would be
-0.0150 (shipped -0.178503).

Run:  python3 bignell1987_h2_check.py          # recompute and compare
      python3 bignell1987_h2_check.py --check  # assert the pinned reduction
"""


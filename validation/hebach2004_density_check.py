"""Hebach, Oberhof & Dahmen (2004) CO2-saturated water densities reduced to
apparent molar volumes: a HELD-OUT check of the route (Paper 23, Table 1: 203
densities, 283-333 K, 1-31 MPa, u(rho) < 0.15%, 39 of them on the vapour-liquid
coexistence line). Table 1 was coordinate-parsed from the PDF text layer and
page-checked row by row against the rendered page on 2026-09-06 (all 203 rows
agree); the cached CSV is the checked copy.

The loading is NOT measured: x is the CO2 solubility in pure water from the
Soreide-Whitson flash (`framework='default'`) at each row's (T, p). By the
project's inclusion rule (direct volumetry and fresh-water inversions at MEASURED
loading are calibrated; solubility-derived volumes are held out) these rows
stay out of the fit.

Reduction per row, per kg water, IAPWS-IF97 water as the gas-free baseline:

    V_imp = ((1000 + m2 M)/rho - 1000/rho_w) / m2     [cm3/mol, rho in g/cm3]

The stated density uncertainty (0.15% of ~1000 kg/m3, so about 1.5 kg/m3)
enters the second term whole: at 284 K and x = 0.035 the CO2-induced density
change is about 13 kg/m3, so u(rho) alone is +/-2 to 3% on V_imp, and more
where x is smaller (the 323-333 K isotherms scatter by 2-2.5 cm3/mol). A 1%
error in the flash x moves V_imp by only about 0.2%.

Run:  python3 hebach2004_density_check.py          # recompute
      python3 hebach2004_density_check.py --check  # assert the pins
"""

